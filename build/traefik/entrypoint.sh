#!/bin/sh

# Traefik entrypoint script that auto-generates TLS configuration from user certificates

CERTS_DIR="/traefik/certs"
DYNAMIC_DIR="/traefik/dynamic"
TLS_CONFIG_FILE="${DYNAMIC_DIR}/auto-tls.yml"

# Deliberately outside the tailscale-peer-*.yaml glob cleared below.
DECLARATION_FILE="spark-http-proxy-declaration.yaml"

generate_tls_config() {
    echo "Scanning for certificates in ${CERTS_DIR}..."

    # Check if certificates directory exists and has files
    if [ ! -d "${CERTS_DIR}" ]; then
        echo "No certificates directory found at ${CERTS_DIR}"
        return
    fi

    # Look for certificate files (both .pem and .crt extensions)
    cert_files=$(find "${CERTS_DIR}" -name "*.pem" -o -name "*.crt" | grep -v "\-key")

    if [ -z "$cert_files" ]; then
        echo "No certificate files found in ${CERTS_DIR}"
        return
    fi

    echo "Found certificates, generating TLS configuration..."

    # Start TLS configuration
    cat > "${TLS_CONFIG_FILE}" << 'EOF'
# Auto-generated TLS configuration from user certificates
tls:
  certificates:
EOF

    # Process each certificate file
    for cert_file in $cert_files; do
        # Get the basename without extension
        cert_base=$(basename "$cert_file" .pem)
        cert_base=$(basename "$cert_base" .crt)

        # Look for corresponding key file
        key_file=""
        for ext in pem crt key; do
            possible_key="${CERTS_DIR}/${cert_base}-key.${ext}"
            if [ -f "$possible_key" ]; then
                key_file="$possible_key"
                break
            fi

            possible_key="${CERTS_DIR}/${cert_base}.key"
            if [ -f "$possible_key" ]; then
                key_file="$possible_key"
                break
            fi
        done

        if [ -n "$key_file" ]; then
            # Extract domains from certificate
            domains=$(openssl x509 -in "$cert_file" -noout -text 2>/dev/null | \
                     grep -A1 "Subject Alternative Name" | \
                     grep "DNS:" | \
                     sed 's/.*DNS://g' | \
                     sed 's/,.*DNS:/ /g' | \
                     sed 's/,.*//g' | \
                     tr -d ' ')

            if [ -n "$domains" ]; then
                echo "  - Adding certificate: $(basename "$cert_file") for domains: $domains"
                cat >> "${TLS_CONFIG_FILE}" << EOF
    - certFile: ${cert_file}
      keyFile: ${key_file}
EOF
            else
                echo "  - Adding certificate: $(basename "$cert_file") (auto-detect domains)"
                cat >> "${TLS_CONFIG_FILE}" << EOF
    - certFile: ${cert_file}
      keyFile: ${key_file}
EOF
            fi
        else
            echo "  - Warning: No key file found for certificate $(basename "$cert_file")"
        fi
    done

    echo "TLS configuration written to ${TLS_CONFIG_FILE}"
}

# Declare what this proxy is, for machines deciding whether to adopt its routes.
#
# Port 30000 identifies a Traefik, not this proxy, and a tailnet may carry an
# unrelated one whose routes must never be adopted. This file is what separates
# the two. It is a middleware because nothing references it, so it changes no
# routing here, and it is written whether or not peer routing is enabled on this
# machine: it says "this is a Spark HTTP Proxy", not "this machine forwards to
# peers". A machine with forwarding switched off is still a good source of
# routes for one that has it on.
write_proxy_declaration() {
    cat > "${DYNAMIC_DIR}/${DECLARATION_FILE}" << 'EOF'
# Declares this proxy to other machines on the tailnet. Referenced by nothing,
# so it applies to no request. Generated at startup; do not edit.
http:
  middlewares:
    spark-http-proxy:
      headers:
        customResponseHeaders:
          X-Spark-Http-Proxy: "1"
EOF
    echo "Wrote proxy declaration to ${DYNAMIC_DIR}/${DECLARATION_FILE}"
}

# Peer routes are generated by a service that only runs when peer routing is
# enabled. With it disabled that service never starts, so nothing else would
# clear the files a previous enabled run left in the shared volume and the proxy
# would keep forwarding to peers. Clear them here, where startup always runs.
remove_peer_config() {
    if [ "${HTTP_PROXY_TAILSCALE_ENABLED}" = "true" ]; then
        return
    fi

    # This glob must never match the declaration file. A machine that has
    # switched forwarding off has to stay discoverable by the machines that have
    # it on, so the two names cannot be allowed to converge.
    for peer_config in "${DYNAMIC_DIR}"/tailscale-peer-*.yaml; do
        [ -e "${peer_config}" ] || continue
        echo "Peer routing is disabled, removing $(basename "${peer_config}")"
        rm -f "${peer_config}"
    done
}

# Declare this proxy to other machines on the tailnet
write_proxy_declaration

# Generate TLS configuration from user certificates
generate_tls_config

# Remove peer routes left behind when peer routing is disabled
remove_peer_config

# Start Traefik with the original arguments
echo "Starting Traefik..."
exec traefik "$@"
